"""Generates docs/asset_manifest.md from the GLB files on disk.

Parses the glTF JSON chunk directly so it needs no Flutter/dart:ui.
    python tool/gen_manifest.py
"""
import glob, json, os, re, struct

def read_glb(path):
    with open(path, 'rb') as f:
        data = f.read()
    magic, version, _ = struct.unpack_from('<III', data, 0)
    assert magic == 0x46546C67, path
    off, gltf = 12, None
    while off + 8 <= len(data):
        length, ctype = struct.unpack_from('<II', data, off)
        chunk = data[off + 8: off + 8 + length]
        if ctype == 0x4E4F534A:
            gltf = json.loads(chunk.decode('utf-8'))
        off += 8 + length + ((4 - length % 4) % 4)
    tris = 0
    for mesh in gltf.get('meshes', []):
        for prim in mesh.get('primitives', []):
            if prim.get('mode', 4) != 4:
                continue
            idx = prim.get('indices')
            if idx is not None:
                tris += gltf['accessors'][idx]['count'] // 3
            else:
                pos = prim['attributes']['POSITION']
                tris += gltf['accessors'][pos]['count'] // 3
    return tris, len(gltf.get('materials', [])), len(data)

def purpose(n):
    if n.startswith('pad_'): return 'Target pad (all worlds)'
    if n.startswith('blade') or n.startswith('default_blade'): return 'Blade / cut FX'
    if n.startswith('crystal') or n.startswith('layered_crystal'): return 'W1 Crystal Workshop'
    if n.startswith('jelly') or n.startswith('layered_jelly'): return 'W2 Jelly Laboratory'
    if any(n.startswith(p) for p in ('apple','watermelon','orange_','pineapple','dragonfruit','fruit_','layered_fruit')): return 'W3 Fruit Foundry'
    if n.startswith('toy_') or n.startswith('block_city') or n.startswith('stacked_toy'): return 'W4 Toy City'
    if any(n.startswith(p) for p in ('gear','layered_engine','turbine','reactor','mechanical_orb','rotating_cylinder','magnet_')): return 'W5 Mechanical Core'
    if 'planet' in n or n.startswith('kanban_'): return 'W6 Kanban Complex'
    return 'Shared'

def sliceable(n):
    return not n.startswith('pad_') and not n.startswith('blade_') and n != 'default_blade.glb'

# Map model -> level ids by scanning the campaign sources in order.
usage = {}
for src in ('lib/game/levels/campaign.dart', 'lib/game/levels/campaign_worlds.dart'):
    text = open(src, encoding='utf-8').read()
    for m in re.finditer(r"id:\s*(\d+)[^)]*?model:\s*'([^']+)'", text, re.S):
        usage.setdefault(m.group(2), []).append(int(m.group(1)))

files = sorted(glob.glob('assets/models/*.glb'))
rows, total_tris, total_kb = [], 0, 0.0
for path in files:
    name = os.path.basename(path)
    tris, mats, size = read_glb(path)
    total_tris += tris; total_kb += size / 1024.0
    source = ('build_01_core.py' if name in ('kanban_core_structure.glb','default_blade.glb')
              or name.startswith('pad_') or name.startswith('blade')
              else 'build_02_library.py')
    lv = sorted(set(usage.get(name, [])))
    lvtext = '-' if not lv else (', '.join(map(str, lv[:4])) + (f', +{len(lv)-4}' if len(lv) > 4 else ''))
    rows.append(f"| {name[:-4]} | `{name}` | `{source}` | {tris} | {mats} | "
                f"{size/1024.0:.1f} | welded vertex cloud | "
                f"{'yes' if sliceable(name) else 'no (static)'} | {purpose(name)} | {lvtext} |")

out = f"""# Asset Manifest

Generated by `python tool/gen_manifest.py` from the GLB files in
`assets/models/`. Do not edit by hand.

Every model is authored procedurally in Blender by `art/blender/build_01_core.py`
and `art/blender/build_02_library.py`, on top of the shared helpers in
`art/blender/kanban_lib.py`. Nothing was modelled by hand and nothing was
downloaded -- the whole library is generated from those scripts, so it can be
rebuilt from scratch at any time.

**Triangle budgets:** particle fragment < 300, small piece < 1,000, normal
slicable object < 8,000, complex structure < 20,000, background prop < 3,000.
Every asset below is comfortably inside its budget; the style is deliberately
faceted low-poly, which is also what the flat-shaded renderer is fastest at.

| Asset | GLB | Blender source | Tris | Mats | Size (KB) | Collider | Runtime-slice | Purpose | Levels |
| --- | --- | --- | ---: | ---: | ---: | --- | --- | --- | --- |
""" + "\n".join(rows) + f"""

**Totals:** {len(files)} models, {total_tris} triangles, {total_kb:.1f} KB.

## Collider policy

Every slicable body uses its own mesh vertices, welded onto a 0.09-unit grid,
as its contact point cloud. No separate collision mesh is authored or shipped:
because the collider is derived from the geometry itself, it regenerates
automatically the moment a piece is sliced, and the newly created cut-face
corners become contact points for free.

## Export settings

GLB, Y-up, applied transforms, flat shading, recalculated outward normals,
origin at the bounds centre, materials exported (one glTF primitive per colour
section), no textures, no animation, no skins. Written by `export_glb()` in
`art/blender/kanban_lib.py`.

## Rendered 2D art

`assets/images/world1..6.png` and `assets/images/store_icon.png` are rendered
from these same GLB files by `art/blender/render_art.py`, so the menu art can
never drift from the assets that appear in play.
"""
open('docs/asset_manifest.md', 'w', encoding='utf-8').write(out)
print(f"docs/asset_manifest.md: {len(files)} assets, {total_tris} tris, {total_kb:.1f} KB")
