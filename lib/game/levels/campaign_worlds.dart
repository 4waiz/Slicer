/// Compact rule builder: material name -> (kind, required zone).
List<MaterialRule> _r(
  Map<String, (MaterialKind, String?)> spec, {
  String? bonusMaterial,
}) => spec.entries
    .map(
      (e) => MaterialRule(
        materialName: e.key,
        kind: e.value.$1,
        zoneId: e.value.$2,
        isBonus: bonusMaterial != null && e.key == bonusMaterial,
      ),
    )
    .toList(growable: false);

