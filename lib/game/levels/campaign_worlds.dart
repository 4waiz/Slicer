// --- Reusable pad layouts (landscape: pads spread across the wide axis) ----

ZoneDef _pad(
  String id,
  String colour,
  String shape,
  double x, {
  double z = 0,
  double w = 2.3,
  ZoneMotion motion = ZoneMotion.still,
  double range = 0,
  double speed = 0.6,
  bool bonus = false,
}) => ZoneDef(
  id: id,
  colorKey: colour,
  shape: shape,
  x: x,
  z: z,
  width: w,
  depth: w,
  motion: motion,
  motionRange: range,
  motionSpeed: speed,
  isBonus: bonus,
);

List<ZoneDef> _two({double spread = 2.4, double w = 2.9}) => [
  _pad('cyan', 'cyan', 'diamond', -spread, w: w),
  _pad('green', 'green', 'square', spread, w: w),
];

List<ZoneDef> _three({double spread = 3.3, double w = 2.5}) => [
  _pad('cyan', 'cyan', 'diamond', -spread, w: w),
  _pad('purple', 'purple', 'triangle', 0, z: -0.5, w: w),
